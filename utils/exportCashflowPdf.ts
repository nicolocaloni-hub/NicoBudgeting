import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { CashflowMovement, CashflowSettings } from '../types/cashflow';

interface ExportOptions {
  productionTitle: string;
  settings: CashflowSettings;
  movements: CashflowMovement[];
}

export const exportCashflowPdf = ({
  productionTitle,
  settings,
  movements
}: ExportOptions) => {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Helper Footer
  const addFooter = (data: { pageNumber: number; pageCount: number }) => {
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(`Pagina ${data.pageNumber} di ${data.pageCount}`, pageWidth - 40, pageHeight - 20, { align: 'right' });
    doc.text("Generated by NicoBudget Pro • Cashflow Intelligence", 40, pageHeight - 20);
  };

  // Titolo e Intestazione
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(15, 23, 42);
  doc.text("DAILY CASHFLOW REPORT", 40, 50);
  
  doc.setFontSize(14);
  doc.setTextColor(79, 70, 229);
  doc.text(productionTitle.toUpperCase(), 40, 70);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100);
  doc.text(`Periodo: ${new Date(settings.startDate).toLocaleDateString('it-IT')} - ${new Date(settings.endDate).toLocaleDateString('it-IT')}`, 40, 85);
  doc.text(`Data Report: ${new Date().toLocaleString('it-IT')}`, 40, 97);

  // Aggregazione per giorno
  const dailyData: Record<string, { in: number; out: number; items: CashflowMovement[] }> = {};
  
  // Prepariamo l'intervallo di date
  const current = new Date(settings.startDate);
  const end = new Date(settings.endDate);
  while (current <= end) {
    const key = current.toISOString().split('T')[0];
    dailyData[key] = { in: 0, out: 0, items: [] };
    current.setDate(current.getDate() + 1);
  }

  // Popoliamo con i movimenti reali
  movements.forEach(m => {
    if (dailyData[m.date]) {
      if (m.type === 'in') dailyData[m.date].in += m.amount;
      else dailyData[m.date].out += m.amount;
      dailyData[m.date].items.push(m);
    }
  });

  // Tabella Riepilogo Giornaliero
  const summaryRows: (string | { content: string; styles: object })[][] = [];
  let runningBalance = settings.initialCash;

  Object.entries(dailyData).sort().forEach(([date, data]) => {
    const dayNet = data.in - data.out;
    runningBalance += dayNet;
    
    summaryRows.push([
      new Date(date).toLocaleDateString('it-IT', { weekday: 'short', day: '2-digit', month: '2-digit' }),
      data.in > 0 ? `+${data.in.toLocaleString('it-IT')}€` : '-',
      data.out > 0 ? `-${data.out.toLocaleString('it-IT')}€` : '-',
      { 
        content: `${dayNet > 0 ? '+' : ''}${dayNet.toLocaleString('it-IT')}€`,
        styles: { textColor: dayNet >= 0 ? [16, 185, 129] : [239, 68, 68], fontStyle: 'bold' }
      },
      { 
        content: `${runningBalance.toLocaleString('it-IT')}€`,
        styles: { fontStyle: 'bold', fillColor: runningBalance < settings.threshold ? [254, 226, 226] : null }
      }
    ]);
  });

  autoTable(doc, {
    startY: 120,
    head: [['DATA', 'ENTRATE', 'USCITE', 'SALDO GG', 'PROGRESSIVO']],
    body: summaryRows,
    theme: 'striped',
    styles: { fontSize: 8, cellPadding: 5 },
    headStyles: { fillColor: [15, 23, 42], textColor: 255, fontStyle: 'bold' },
    columnStyles: { 
      1: { halign: 'right' }, 
      2: { halign: 'right' }, 
      3: { halign: 'right' }, 
      4: { halign: 'right', cellWidth: 80 } 
    },
    didDrawPage: addFooter
  });

  // Seconda Tabella: Dettaglio Movimenti
  const movementsRows: (string | { content: string; styles: object })[][] = [];
  movements.sort((a, b) => a.date.localeCompare(b.date)).forEach(m => {
    movementsRows.push([
      new Date(m.date).toLocaleDateString('it-IT'),
      m.category.toUpperCase(),
      m.note,
      m.type === 'in' ? 'ENTRATA' : 'USCITA',
      { 
        content: `${m.type === 'in' ? '+' : '-'}${m.amount.toLocaleString('it-IT')}€`,
        styles: { textColor: m.type === 'in' ? [16, 185, 129] : [239, 68, 68], fontStyle: 'bold', halign: 'right' }
      }
    ]);
  });

  if (movementsRows.length > 0) {
    doc.addPage();
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text("ANALISI DETTAGLIATA MOVIMENTI", 40, 50);

    autoTable(doc, {
      startY: 70,
      head: [['DATA', 'CATEGORIA', 'DESCRIZIONE', 'TIPO', 'IMPORTO']],
      body: movementsRows,
      theme: 'plain',
      styles: { fontSize: 7, cellPadding: 4 },
      headStyles: { fillColor: [79, 70, 229], textColor: 255 },
      columnStyles: { 4: { halign: 'right' } },
      didDrawPage: addFooter
    });
  }

  const fileName = `cashflow_${productionTitle.toLowerCase().replace(/\s+/g, '_')}_report.pdf`;
  return { doc, fileName };
};