import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Category, Fringe } from '../types';

interface InfoRow {
  label: string;
  value: string;
}

interface ExportOptions {
  productionTitle: string;
  version: string;
  exportDate: string;
  includeCover: boolean;
  leftInfo: InfoRow[];
  rightInfo: InfoRow[];
  categories: Category[];
  fringes: Fringe[];
}

export const exportBudgetPdf = ({
  productionTitle,
  version,
  exportDate,
  includeCover,
  leftInfo,
  rightInfo,
  categories
}: ExportOptions) => {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const currencyFormatter = new Intl.NumberFormat('it-IT', { style: 'currency', currency: 'EUR' });
  const displayDate = new Date(exportDate).toLocaleDateString('it-IT');
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const grandTotal = categories.reduce((sum, c) => sum + c.total, 0);

  // Helper for footer and page numbers
  const addFooter = (data: { pageNumber: number; pageCount: number }) => {
    const str = `Pagina ${data.pageNumber} di ${data.pageCount}`;
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(str, pageWidth - 40, pageHeight - 20, { align: 'right' });
    doc.text("Generated by NicoBudget Pro", 40, pageHeight - 20);
  };

  // 1. COPERTINA
  if (includeCover) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(28);
    doc.setTextColor(15, 23, 42);
    doc.text(productionTitle.toUpperCase(), pageWidth / 2, pageHeight * 0.3, { align: 'center', maxWidth: pageWidth - 100 });

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(14);
    doc.text(`VERSIONE: ${version}`, pageWidth / 2, pageHeight * 0.38, { align: 'center' });
    doc.text(`DATA: ${displayDate}`, pageWidth / 2, pageHeight * 0.41, { align: 'center' });

    doc.setDrawColor(79, 70, 229);
    doc.setLineWidth(1.5);
    doc.line(pageWidth * 0.2, pageHeight * 0.5, pageWidth * 0.8, pageHeight * 0.5);

    doc.setFontSize(12);
    doc.text("STIMA BUDGET TOTALE", pageWidth / 2, pageHeight * 0.55, { align: 'center' });
    doc.setFontSize(24);
    doc.setTextColor(79, 70, 229);
    doc.text(currencyFormatter.format(grandTotal), pageWidth / 2, pageHeight * 0.6, { align: 'center' });

    doc.addPage();
  }

  // 2. HEADER BUDGET (Info Colonne)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  doc.text(`BUDGET "${productionTitle.toUpperCase()}"`, 40, 45);
  doc.setFontSize(10);
  doc.text(`Versione: ${version} | Data: ${displayDate}`, 40, 60);

  // Metadata Box
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.rect(40, 75, pageWidth - 80, 100);

  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  
  // Render Left Column
  let leftY = 90;
  leftInfo.filter(i => i.label && i.value).forEach(item => {
    doc.setFont('helvetica', 'bold');
    doc.text(`${item.label}:`, 50, leftY);
    doc.setFont('helvetica', 'normal');
    doc.text(item.value, 130, leftY);
    leftY += 12;
  });

  // Render Right Column
  let rightY = 90;
  rightInfo.filter(i => i.label && i.value).forEach(item => {
    doc.setFont('helvetica', 'bold');
    doc.text(`${item.label}:`, pageWidth / 2 + 10, rightY);
    doc.setFont('helvetica', 'normal');
    doc.text(item.value, pageWidth / 2 + 100, rightY);
    rightY += 12;
  });

  // 3. TABELLA BUDGET (EP-Style)
  const tableData: (string | { content: string; styles: object })[][] = [];
  categories.filter(c => c.total > 0).forEach(cat => {
    // Riga Categoria
    tableData.push([
      { content: cat.code, styles: { fontStyle: 'bold', fillColor: [241, 245, 249] } },
      { content: cat.name.toUpperCase(), styles: { fontStyle: 'bold', fillColor: [241, 245, 249] } },
      { content: currencyFormatter.format(cat.total), styles: { fontStyle: 'bold', halign: 'right', fillColor: [241, 245, 249] } }
    ]);

    // Righe Account
    cat.accounts.filter(a => a.total > 0).forEach(acc => {
      tableData.push([
        { content: acc.code, styles: { textColor: 100 } },
        { content: `    ${acc.name}`, styles: { textColor: 80 } }, // Indentazione
        { content: currencyFormatter.format(acc.total), styles: { halign: 'right' } }
      ]);
    });

    // Riga Totale Categoria (Subfooter)
    tableData.push([
      '',
      { content: `Account Total for ${cat.code}`, styles: { fontStyle: 'italic', textColor: 150, fontSize: 8 } },
      { content: currencyFormatter.format(cat.total), styles: { halign: 'right', fontStyle: 'bold', textColor: [79, 70, 229] } }
    ]);
  });

  autoTable(doc, {
    startY: 190,
    head: [['ACCT#', 'DESCRIPTION', 'TOTAL']],
    body: tableData,
    theme: 'plain',
    styles: { fontSize: 8, cellPadding: 4 },
    headStyles: { fillColor: [15, 23, 42], textColor: 255, fontStyle: 'bold' },
    columnStyles: { 0: { cellWidth: 50 }, 2: { cellWidth: 100, halign: 'right' } },
    didDrawPage: addFooter,
    margin: { bottom: 40 }
  });

  // Final Grand Total row at the end of all pages
  const finalY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(255);
  doc.setFillColor(79, 70, 229);
  doc.rect(40, finalY + 5, pageWidth - 80, 25, 'F');
  doc.text("GRAND TOTAL", 50, finalY + 21);
  doc.text(currencyFormatter.format(grandTotal), pageWidth - 50, finalY + 21, { align: 'right' });

  const fileName = `${productionTitle.toLowerCase().replace(/\s+/g, '_')}_budget.pdf`;
  doc.save(fileName);
};